#!/usr/bin/env node
// Builds the checked-in quiz data files from a private source question pool.
// Usage: node scripts/build-quiz-data.mjs /path/to/cuga_quiz_pool_v3.json
//
// The source file (plaintext answers + explanations) must never be committed
// to this repo. This script only ever writes the three derived files below.

import { readFileSync, writeFileSync } from "node:fs";
import { createHash } from "node:crypto";
import { fileURLToPath } from "node:url";
import path from "node:path";

const PEPPER = "cuga-quiz-pepper-v1";

const sourcePath = process.argv[2];
if (!sourcePath) {
  console.error("Usage: node scripts/build-quiz-data.mjs <path-to-source-pool.json>");
  process.exit(1);
}

const pool = JSON.parse(readFileSync(sourcePath, "utf-8"));
const questions = pool.questions;

const outDir = path.join(path.dirname(fileURLToPath(import.meta.url)), "..", "src", "data");

const header = (name) => `// AUTO-GENERATED by scripts/build-quiz-data.mjs — do not hand edit.
// Do not commit the source pool file this was built from.
`;

function sha256Hex(input) {
  return createHash("sha256").update(input, "utf-8").digest("hex");
}

const quizPool = questions.map((q) => ({
  id: q.id,
  difficulty: q.difficulty,
  question: q.question,
  options: q.options.map((o) => ({ id: o.id, text: o.text })),
}));

const answerKey = Object.fromEntries(
  questions.map((q) => [q.id, sha256Hex(`${q.id}::${q.answer}::${PEPPER}`)])
);

const explanations = Object.fromEntries(
  questions.map((q) => [q.id, { explanation: q.explanation, source: q.source ?? null }])
);

writeFileSync(
  path.join(outDir, "quizPool.ts"),
  `${header()}
import type { QuizQuestion } from "../lib/quizTypes";

export const quizPool: QuizQuestion[] = ${JSON.stringify(quizPool, null, 2)};
`
);

writeFileSync(
  path.join(outDir, "quizAnswerKey.ts"),
  `${header()}
// Maps questionId -> sha256(\`\${questionId}::\${correctOptionId}::PEPPER\`).
// See src/lib/quizCrypto.ts for why this is obfuscation, not real secrecy.
export const quizAnswerKey: Record<string, string> = ${JSON.stringify(answerKey, null, 2)};
`
);

writeFileSync(
  path.join(outDir, "quizExplanations.ts"),
  `${header()}
export interface QuizExplanation {
  explanation: string;
  source: string | null;
}

// Loaded via dynamic import() only when the results screen renders.
export const quizExplanations: Record<string, QuizExplanation> = ${JSON.stringify(explanations, null, 2)};
`
);

const sources = pool.sources ?? {};

writeFileSync(
  path.join(outDir, "quizSources.ts"),
  `${header()}
export interface QuizSources {
  talk?: string;
  site?: string;
  docs?: string;
  repos?: string[];
}

// Where the question pool's facts come from. No answer content — safe to ship as-is.
export const quizSources: QuizSources = ${JSON.stringify(sources, null, 2)};
`
);

const byDifficulty = questions.reduce((acc, q) => {
  acc[q.difficulty] = (acc[q.difficulty] ?? 0) + 1;
  return acc;
}, {});

console.log(`Wrote ${questions.length} questions to src/data/*.ts`);
console.log("By difficulty:", byDifficulty);
